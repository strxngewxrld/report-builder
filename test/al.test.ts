import { test } from 'node:test';
import assert from 'node:assert/strict';
import { expectedDataset, parseAl } from '../src/al/parser';

const REPORT = `
namespace Contoso.Sales;

using Microsoft.Sales.Customer;

/// <summary>Invoice with lines</summary>
report 50100 "Contoso Invoice"
{
    Caption = 'Contoso Invoice';
    DefaultRenderingLayout = RDLCLayout;

    dataset
    {
        dataitem(Header; "Sales Invoice Header")
        {
            RequestFilterFields = "No.";
            column(No_Header; "No.") { IncludeCaption = true; }
            column(CompanyName; CompanyProperty.DisplayName()) { }
            // column(Commented; "Commented") { }
            /* column(Blocked; Blocked) */
            column(Total; Format(Header.Amount, 0, '<Precision,2:2><Standard Format,0>'))
            {
                IncludeCaption = false;
            }
            dataitem(Line; "Sales Invoice Line")
            {
                DataItemLink = "Document No." = field("No.");
                column(Description_Line; Description) { IncludeCaption = true; }
                column(Amount_Line; Amount) { AutoFormatType = 1; }

                trigger OnAfterGetRecord()
                begin
                    if Line.Type = Line.Type::" " then
                        CurrReport.Skip();
                end;
            }
        }
        dataitem(Totals; Integer)
        {
            DataItemTableView = where(Number = const(1));
            column(Number; Number) { }
        }
    }

    requestpage
    {
        layout
        {
            area(Content) { field(ShowLines; ShowLines) { Caption = 'Show lines'; } }
        }
    }

    rendering
    {
        layout(RDLCLayout)
        {
            Type = RDLC;
            LayoutFile = './src/layouts/ContosoInvoice.rdlc';
        }
        layout(WordLayout) { Type = Word; LayoutFile = './src/layouts/ContosoInvoice.docx'; }
    }

    labels
    {
        InvoiceLbl = 'Invoice';
        PageLbl = 'Page %1 of %2', Comment = '%1 = page, %2 = total', MaxLength = 30;
        QuoteLbl = 'It''s quoted', Locked = true;
    }

    var
        ShowLines: Boolean;

    procedure SetShowLines(NewShowLines: Boolean)
    begin
        ShowLines := NewShowLines;
        Report.Run(Report::"Contoso Invoice");
    end;
}

reportextension 50101 "Contoso Invoice Ext" extends "Contoso Invoice"
{
    dataset
    {
        add(Header) { column(YourReference; "Your Reference") { IncludeCaption = true; } }
        addlast(Line) { dataitem(Comment; "Sales Comment Line") { column(CommentText; Comment) { } } }
    }
    rendering
    {
        layout(ExtLayout) { Type = RDLC; LayoutFile = 'ExtInvoice.rdlc'; }
    }
}

report 50102 LegacyReport
{
    RDLCLayout = './Legacy.rdlc';
    WordLayout = './Legacy.docx';
    DefaultLayout = RDLC;
    dataset { dataitem(Customer; Customer) { column(Name; Name) { } } }
}
`;

test('report: data items, columns, labels, layouts', () => {
  const [rep, ext, legacy] = parseAl(REPORT);
  assert.equal(rep.kind, 'report');
  assert.equal(rep.id, 50100);
  assert.equal(rep.name, 'Contoso Invoice');
  assert.deepEqual(rep.dataItems.map(d => [d.name, d.table]), [['Header', 'Sales Invoice Header'], ['Totals', 'Integer']]);
  const header = rep.dataItems[0];
  assert.deepEqual(header.columns.map(c => c.name), ['No_Header', 'CompanyName', 'Total']);
  assert.equal(header.columns[2].source, "Format(Header.Amount, 0, '<Precision,2:2><Standard Format,0>')");
  assert.deepEqual(header.children.map(d => d.name), ['Line']);
  assert.deepEqual(header.children[0].columns.map(c => [c.name, c.includeCaption, c.dataItem]), [['Description_Line', true, 'Line'], ['Amount_Line', false, 'Line']]);
  assert.deepEqual(rep.labels.map(l => [l.name, l.text]), [['InvoiceLbl', 'Invoice'], ['PageLbl', 'Page %1 of %2'], ['QuoteLbl', "It's quoted"]]);
  assert.deepEqual(rep.layouts.map(l => [l.name, l.type, l.file]), [['RDLCLayout', 'RDLC', './src/layouts/ContosoInvoice.rdlc'], ['WordLayout', 'Word', './src/layouts/ContosoInvoice.docx']]);
  // positions point at the column name (0-based)
  const pos = header.columns[0].pos;
  assert.equal(REPORT.split('\n')[pos.line].slice(pos.character, pos.character + 9), 'No_Header');

  assert.deepEqual([legacy.name, legacy.layouts.map(l => [l.type, l.file])], ['LegacyReport', [['RDLC', './Legacy.rdlc'], ['Word', './Legacy.docx']]]);

  assert.equal(ext.kind, 'reportextension');
  assert.equal(ext.extends, 'Contoso Invoice');
  assert.deepEqual(ext.additions.map(a => [a.target, a.columns.map(c => c.name), a.dataItems.map(d => d.name)]), [['Header', ['YourReference'], []], ['Line', [], ['Comment']]]);
});

test('expected dataset as generated by the AL compiler', () => {
  const [rep, ext] = parseAl(REPORT);
  const e = expectedDataset(rep);
  assert.deepEqual(e.fields, ['No_Header', 'CompanyName', 'Total', 'Description_Line', 'Amount_Line', 'Number']);
  assert.deepEqual(e.parameters, ['InvoiceLbl', 'PageLbl', 'QuoteLbl', 'No_HeaderCaption', 'Description_LineCaption']);
  assert.equal(e.complete, true);

  const withBase = expectedDataset(ext, rep);
  assert.deepEqual(withBase.fields.slice(-2), ['YourReference', 'CommentText']);
  assert.ok(withBase.parameters.includes('YourReferenceCaption'));
  assert.equal(withBase.complete, true);
  assert.equal(expectedDataset(ext).complete, false, 'base report unknown');
});
