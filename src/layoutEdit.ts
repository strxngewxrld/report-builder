// Text edits on a layout made in the extension host, so they can go into one WorkspaceEdit with AL edits (one undo
// step across both files). Source-preserving: only the value concerned changes.

const escText = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const escRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Replaces the value of a textbox with a single text run. Returns the offsets and the new <Value> element, or null
 * when there is no such textbox (unknown name, several runs or paragraphs).
 */
export function textboxValueEdit(xml: string, name: string, value: string): { start: number; end: number; text: string } | null {
  const attr = name.replace(/&/g, '&amp;').replace(/"/g, '&quot;');
  const open = new RegExp(`<Textbox\\s[^>]*\\bName="${escRe(attr)}"[^>]*>`).exec(xml);
  if (!open) return null;
  const close = xml.indexOf('</Textbox>', open.index);
  if (close < 0) return null;
  const body = xml.slice(open.index, close);
  if ((body.match(/<Paragraph[\s>]/g) ?? []).length !== 1 || (body.match(/<TextRun[\s>]/g) ?? []).length !== 1) return null;
  const run = body.indexOf('<TextRun');
  const v = /<Value(\s[^>]*?)?(?:\s*\/>|>[\s\S]*?<\/Value>)/.exec(body.slice(run));
  if (!v) return null;
  // EvaluationMode="Constant" would show the expression as text
  const attrs = (v[1] ?? '').replace(/\s*EvaluationMode="[^"]*"/, '');
  const start = open.index + run + v.index;
  return { start, end: start + v[0].length, text: `<Value${attrs}>${escText(value)}</Value>` };
}

/**
 * Renames a dataset column in a layout: field references (Fields!X, also the generated XFormat), the caption
 * parameter (Parameters!XCaption), the dataset's field and parameter declarations, and textboxes named after the
 * column (with their ReportItems! references) unless the new name is taken. Returns the new text and the number of
 * replacements.
 */
export function renameColumnInLayout(xml: string, from: string, to: string): { text: string; count: number } {
  let count = 0;
  const f = escRe(from);
  // names of report items, groups etc. are unique in a report; dataset fields and parameters have their own scope
  const taken = new RegExp(`<(?!Field\\b|ReportParameter\\b)[\\w:]+\\s[^>]*?\\bName="${escRe(to)}"`).test(xml);
  const sub = (re: RegExp, by: (m: string, ...g: string[]) => string) => {
    xml = xml.replace(re, (m, ...g) => { count++; return by(m, ...(g as string[])); });
  };
  // expressions
  sub(new RegExp(`(Fields!)${f}(Format)?\\b`, 'g'), (_, p, fmt) => `${p}${to}${fmt ?? ''}`);
  sub(new RegExp(`(Parameters!)${f}Caption\\b`, 'g'), (_, p) => `${p}${to}Caption`);
  // dataset and parameter declarations (as generated by the AL compiler)
  sub(new RegExp(`(<Field Name=")${f}(Format)?(")`, 'g'), (_, a, fmt, b) => `${a}${to}${fmt ?? ''}${b}`);
  sub(new RegExp(`(<DataField>)${f}(Format)?(</DataField>)`, 'g'), (_, a, fmt, b) => `${a}${to}${fmt ?? ''}${b}`);
  sub(new RegExp(`(<ReportParameter Name=")${f}Caption(")`, 'g'), (_, a, b) => `${a}${to}Caption${b}`);
  sub(new RegExp(`(<(ParameterName|Prompt)>)${f}Caption(</\\2>)`, 'g'), (_, a, _t, b) => `${a}${to}Caption${b}`);
  // report items named after the column (Business Central layouts do that), if the name is free
  if (!taken) {
    sub(new RegExp(`(<(?:Textbox|Image|Rectangle|Tablix|Chart|Line|Subreport)\\s[^>]*?Name=")${f}(")`, 'g'), (_, a, b) => `${a}${to}${b}`);
    sub(new RegExp(`(<rd:DefaultName>)${f}(</rd:DefaultName>)`, 'g'), (_, a, b) => `${a}${to}${b}`);
    sub(new RegExp(`(ReportItems!)${f}\\b`, 'g'), (_, p) => `${p}${to}`);
    sub(new RegExp(`(<(?:ToggleItem|SortExpressionScope)>)${f}(</)`, 'g'), (_, a, b) => `${a}${to}${b}`);
  }
  return { text: xml, count };
}
